#!/usr/bin/env node

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const sourceURL = "https://jpservices.nationalrail.co.uk/stations";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appOutput = resolve(root, "Sources/PlatformApp/Resources/stations.json");
const workerOutput = resolve(root, "worker/src/stations.generated.ts");

const response = await fetch(sourceURL, {
  headers: { Accept: "application/json" },
});

if (!response.ok) {
  throw new Error(`National Rail station catalogue returned ${response.status}`);
}

const raw = await response.json();
const stations = raw
  .filter((station) => station.darwinState === 4)
  .filter((station) => /^[A-Z]{3}$/.test(station.crsCode))
  .map((station) => ({ crs: station.crsCode, name: station.name }))
  .sort((left, right) => left.name.localeCompare(right.name, "en-GB"));

if (stations.length < 2_000) {
  throw new Error(`Refusing to write an unexpectedly small catalogue (${stations.length})`);
}

await writeFile(appOutput, `${JSON.stringify(stations, null, 2)}\n`);

const crsCodes = stations.map((station) => station.crs);
await writeFile(
  workerOutput,
  `// Generated by scripts/update-stations.mjs. Do not edit.\n` +
    `export const VALID_CRS_CODES = new Set(${JSON.stringify(crsCodes)});\n`,
);

console.log(`Wrote ${stations.length} Darwin stations.`);
